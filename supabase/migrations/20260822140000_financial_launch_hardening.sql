-- ---------------------------------------------------------------------------
-- 5) Source-tracked posting engine (exactly one entry per business event).
-- ---------------------------------------------------------------------------
-- The legacy implementation cast the whole date+sequence string to int4 and
-- already overflows in production (for example 20260720260). Serialize number
-- allocation per organization and only parse the trailing sequence as bigint.
CREATE OR REPLACE FUNCTION public._next_entry_number(_org uuid)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_next bigint;
  v_prefix text := 'JE-'||to_char(CURRENT_DATE,'YYYYMM')||'-';
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(_org::text,0));
  SELECT COALESCE(MAX(x.seq),0)+1 INTO v_next
  FROM (
    SELECT substring(entry_number FROM '([0-9]+)$')::bigint AS seq
    FROM public.journal_entries
    WHERE organization_id=_org AND entry_number LIKE v_prefix||'%'
  ) x;
  RETURN v_prefix||lpad(v_next::text,5,'0');
END;
$$;

CREATE OR REPLACE FUNCTION public.post_booking_cost(_booking_id uuid)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  b public.bookings%ROWTYPE;
  v_je uuid;
  v_cogs uuid;
  v_ap uuid;
  v_cost_code text;
BEGIN
  SELECT * INTO b FROM public.bookings WHERE id=_booking_id;
  IF NOT FOUND THEN RETURN NULL; END IF;

  SELECT id INTO v_je FROM public.journal_entries
  WHERE organization_id=b.organization_id AND source_type='booking_cost' AND source_id=b.id;

  IF b.is_demo OR COALESCE(b.status,'pending') NOT IN ('confirmed','completed')
     OR COALESCE(b.cost_price,0) <= 0 THEN
    IF v_je IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
    ) THEN
      DELETE FROM public.journal_entries WHERE id=v_je;
    END IF;
    RETURN NULL;
  END IF;

  IF v_je IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
  ) THEN
    RETURN v_je;
  END IF;

  v_cost_code := CASE b.booking_type
    WHEN 'flight' THEN '5010'
    WHEN 'transport' THEN '5020'
    WHEN 'car_rental' THEN '5030'
    ELSE '5000'
  END;
  v_cogs := COALESCE(public._resolve_account(b.organization_id,v_cost_code),
                     public._resolve_account(b.organization_id,'5000'));
  v_ap := public._resolve_account(b.organization_id,'2000');
  IF v_cogs IS NULL OR v_ap IS NULL THEN
    RAISE EXCEPTION 'Missing COGS/AP account for organization %', b.organization_id;
  END IF;

  DELETE FROM public.journal_entries WHERE id=v_je AND NOT is_locked;
  INSERT INTO public.journal_entries (
    organization_id,entry_number,entry_date,reference_type,reference_id,description,
    total_debit,total_credit,status,currency,source_type,source_id,booking_id,
    functional_currency,fx_rate,posted_at,auto_generated
  ) VALUES (
    b.organization_id,public._next_entry_number(b.organization_id),
    COALESCE(b.start_date,b.created_at::date,CURRENT_DATE),'booking_cost',b.id,
    'تكلفة حجز '||b.booking_number,b.cost_price,b.cost_price,'posted',
    COALESCE(b.currency,'EGP'),'booking_cost',b.id,b.id,COALESCE(b.currency,'EGP'),1,now(),true
  ) RETURNING id INTO v_je;

  INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
  VALUES
    (v_je,v_cogs,b.cost_price,0,'تكلفة حجز '||b.booking_number,1),
    (v_je,v_ap,0,b.cost_price,'ذمم المورد - '||COALESCE(b.supplier_name,''),2);
  RETURN v_je;
END;
$$;

CREATE OR REPLACE FUNCTION public.post_invoice(_invoice_id uuid)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  i public.invoices%ROWTYPE;
  v_je uuid;
  v_ar uuid;
  v_revenue uuid;
  v_tax uuid;
  v_revenue_code text;
  v_net numeric;
BEGIN
  SELECT * INTO i FROM public.invoices WHERE id=_invoice_id;
  IF NOT FOUND OR i.organization_id IS NULL THEN RETURN NULL; END IF;

  SELECT id INTO v_je FROM public.journal_entries
  WHERE organization_id=i.organization_id AND source_type='invoice' AND source_id=i.id;

  IF i.is_demo OR COALESCE(i.status,'draft') IN ('draft','cancelled')
     OR COALESCE(i.final_amount,0) <= 0 THEN
    IF v_je IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
    ) THEN
      DELETE FROM public.journal_entries WHERE id=v_je;
    END IF;
    RETURN NULL;
  END IF;

  IF v_je IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
  ) THEN
    RETURN v_je;
  END IF;

  v_revenue_code := CASE i.booking_type
    WHEN 'hotel' THEN '4000'
    WHEN 'flight' THEN '4010'
    WHEN 'transport' THEN '4020'
    WHEN 'car_rental' THEN '4030'
    ELSE '4040'
  END;
  v_ar := public._resolve_account(i.organization_id,'1100');
  v_revenue := COALESCE(public._resolve_account(i.organization_id,v_revenue_code),
                        public._resolve_account(i.organization_id,'4000'));
  v_tax := public._resolve_account(i.organization_id,'2100');
  v_net := round(COALESCE(i.subtotal,0)-COALESCE(i.discount_amount,0),2);

  IF v_ar IS NULL OR v_revenue IS NULL OR (COALESCE(i.vat_amount,0)>0 AND v_tax IS NULL) THEN
    RAISE EXCEPTION 'Missing AR/revenue/tax account for organization %', i.organization_id;
  END IF;
  IF abs(v_net + COALESCE(i.vat_amount,0) - i.final_amount) > 0.01 THEN
    RAISE EXCEPTION 'Invoice % is not balanced after discount and VAT', i.invoice_number;
  END IF;

  DELETE FROM public.journal_entries WHERE id=v_je AND NOT is_locked;
  INSERT INTO public.journal_entries (
    organization_id,entry_number,entry_date,reference_type,reference_id,description,
    total_debit,total_credit,status,currency,source_type,source_id,booking_id,
    functional_currency,fx_rate,posted_at,auto_generated
  ) VALUES (
    i.organization_id,public._next_entry_number(i.organization_id),
    COALESCE(i.issued_date,i.created_at::date,CURRENT_DATE),'invoice',i.id,
    'فاتورة '||i.invoice_number,i.final_amount,i.final_amount,'posted',
    COALESCE(i.currency,'EGP'),'invoice',i.id,i.booking_id,COALESCE(i.currency,'EGP'),1,now(),true
  ) RETURNING id INTO v_je;

  INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
  VALUES (v_je,v_ar,i.final_amount,0,'ذمم العميل - '||COALESCE(i.customer_name,''),1);
  IF v_net > 0 THEN
    INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
    VALUES (v_je,v_revenue,0,v_net,'صافي إيراد فاتورة '||i.invoice_number,2);
  END IF;
  IF COALESCE(i.vat_amount,0)>0 THEN
    INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
    VALUES (v_je,v_tax,0,i.vat_amount,'ضريبة القيمة المضافة',3);
  END IF;
  RETURN v_je;
END;
$$;

CREATE OR REPLACE FUNCTION public.post_customer_payment(_payment_id uuid)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p public.customer_payments%ROWTYPE;
  v_je uuid;
  v_cash uuid;
  v_ar uuid;
  v_advance uuid;
  v_treasury_kind text;
  v_treasury_currency text;
  v_allocated numeric;
  v_unallocated numeric;
BEGIN
  SELECT * INTO p FROM public.customer_payments WHERE id=_payment_id;
  IF NOT FOUND THEN RETURN NULL; END IF;

  SELECT id INTO v_je FROM public.journal_entries
  WHERE organization_id=p.organization_id AND source_type='customer_payment' AND source_id=p.id;

  IF p.is_demo OR p.status<>'completed' THEN
    IF v_je IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
    ) THEN DELETE FROM public.journal_entries WHERE id=v_je; END IF;
    RETURN NULL;
  END IF;
  IF v_je IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
  ) THEN RETURN v_je; END IF;

  IF p.treasury_account_id IS NOT NULL THEN
    SELECT treasury_kind,COALESCE(currency,'EGP')
      INTO v_treasury_kind,v_treasury_currency
    FROM public.bank_accounts
    WHERE id=p.treasury_account_id AND organization_id=p.organization_id AND is_active;
    IF NOT FOUND OR v_treasury_currency<>p.currency THEN
      RAISE EXCEPTION 'Customer payment treasury is missing, inactive, or uses another currency';
    END IF;
  ELSIF p.payment_method<>'cash' THEN
    RAISE EXCEPTION 'A treasury account is required for non-cash customer payments';
  END IF;
  v_cash := public._resolve_account(
    p.organization_id,
    CASE WHEN COALESCE(v_treasury_kind,p.payment_method)='cash' THEN '1000' ELSE '1010' END
  );
  v_ar := public._resolve_account(p.organization_id,'1100');
  v_advance := public._resolve_account(p.organization_id,'2050');
  SELECT COALESCE(SUM(amount),0) INTO v_allocated
  FROM public.customer_payment_allocations WHERE payment_id=p.id;
  v_allocated := LEAST(v_allocated,p.amount);
  v_unallocated := p.amount-v_allocated;

  IF v_cash IS NULL OR (v_allocated>0 AND v_ar IS NULL)
     OR (v_unallocated>0 AND v_advance IS NULL) THEN
    RAISE EXCEPTION 'Missing cash/AR/customer-advance account for organization %', p.organization_id;
  END IF;

  DELETE FROM public.journal_entries WHERE id=v_je AND NOT is_locked;
  INSERT INTO public.journal_entries (
    organization_id,entry_number,entry_date,reference_type,reference_id,description,
    total_debit,total_credit,status,currency,source_type,source_id,booking_id,
    functional_currency,fx_rate,posted_at,auto_generated
  ) VALUES (
    p.organization_id,public._next_entry_number(p.organization_id),p.payment_date,
    'customer_payment',p.id,'دفعة عميل '||COALESCE(p.reference_number,p.id::text),
    p.amount,p.amount,'posted',p.currency,'customer_payment',p.id,p.booking_id,
    p.currency,p.exchange_rate,now(),true
  ) RETURNING id INTO v_je;

  INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
  VALUES (v_je,v_cash,p.amount,0,'تحصيل من العميل',1);
  IF v_allocated>0 THEN
    INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
    VALUES (v_je,v_ar,0,v_allocated,'تسوية ذمم عميل',2);
  END IF;
  IF v_unallocated>0 THEN
    INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
    VALUES (v_je,v_advance,0,v_unallocated,'دفعة مقدمة/رصيد دائن للعميل',3);
  END IF;
  RETURN v_je;
END;
$$;

-- Imported invoices often contain a paid total but predate the structured
-- customer_payments table. Post only the residual paid amount that is not
-- already represented by a payment allocation, so AR remains correct without
-- duplicating modern receipts.
CREATE OR REPLACE FUNCTION public.post_invoice_legacy_receipt(_invoice_id uuid)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  i public.invoices%ROWTYPE;
  v_je uuid;
  v_bank uuid;
  v_ar uuid;
  v_allocated numeric;
  v_residual numeric;
BEGIN
  SELECT * INTO i FROM public.invoices WHERE id=_invoice_id;
  IF NOT FOUND OR i.organization_id IS NULL THEN RETURN NULL; END IF;
  SELECT id INTO v_je FROM public.journal_entries
  WHERE organization_id=i.organization_id
    AND source_type='legacy_invoice_receipt' AND source_id=i.id;

  SELECT COALESCE(SUM(a.amount),0) INTO v_allocated
  FROM public.customer_payment_allocations a
  JOIN public.customer_payments p ON p.id=a.payment_id AND p.status='completed'
  WHERE a.invoice_id=i.id;
  v_residual := GREATEST(COALESCE(i.total_paid_amount,0)-v_allocated,0);

  IF i.is_demo OR v_residual<=0 THEN
    IF v_je IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
    ) THEN DELETE FROM public.journal_entries WHERE id=v_je; END IF;
    RETURN NULL;
  END IF;
  IF v_je IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.journal_entries WHERE id=v_je AND is_locked
  ) THEN RETURN v_je; END IF;

  v_bank:=COALESCE(public._resolve_account(i.organization_id,'1010'),
                   public._resolve_account(i.organization_id,'1000'));
  v_ar:=public._resolve_account(i.organization_id,'1100');
  IF v_bank IS NULL OR v_ar IS NULL THEN
    RAISE EXCEPTION 'Missing bank/AR account for organization %',i.organization_id;
  END IF;

  DELETE FROM public.journal_entries WHERE id=v_je AND NOT is_locked;
  INSERT INTO public.journal_entries(
    organization_id,entry_number,entry_date,reference_type,reference_id,description,
    total_debit,total_credit,status,currency,source_type,source_id,booking_id,
    functional_currency,fx_rate,posted_at,auto_generated
  ) VALUES (
    i.organization_id,public._next_entry_number(i.organization_id),
    COALESCE(i.issued_date,i.created_at::date,CURRENT_DATE),'legacy_invoice_receipt',i.id,
    'تحصيل تاريخي مثبت على الفاتورة '||i.invoice_number,v_residual,v_residual,'posted',
    COALESCE(i.currency,'EGP'),'legacy_invoice_receipt',i.id,i.booking_id,
    COALESCE(i.currency,'EGP'),1,now(),true
  ) RETURNING id INTO v_je;
  INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
  VALUES
    (v_je,v_bank,v_residual,0,'تحصيل تاريخي - وسيلة السداد غير مستوردة',1),
    (v_je,v_ar,0,v_residual,'تسوية ذمم فاتورة تاريخية',2);
  RETURN v_je;
END;
$$;

