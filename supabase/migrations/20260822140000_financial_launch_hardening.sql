ON public.bookings
FOR EACH ROW EXECUTE FUNCTION public.normalize_booking_financials();

CREATE OR REPLACE FUNCTION public.normalize_invoice_totals()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_net numeric;
BEGIN
  NEW.subtotal := COALESCE(NEW.subtotal, 0);
  NEW.discount_amount := COALESCE(NEW.discount_amount, 0);
  NEW.vat_rate := COALESCE(NEW.vat_rate, 0);
  NEW.total_paid_amount := COALESCE(NEW.total_paid_amount, 0);

  IF NEW.subtotal < 0 OR NEW.discount_amount < 0 OR NEW.vat_rate < 0
     OR NEW.total_paid_amount < 0 THEN
    RAISE EXCEPTION 'Invoice amounts and VAT rate must be non-negative';
  END IF;
  IF NEW.discount_amount > NEW.subtotal THEN
    RAISE EXCEPTION 'Invoice discount cannot exceed subtotal';
  END IF;

  v_net := NEW.subtotal - NEW.discount_amount;
  NEW.vat_amount := round(v_net * NEW.vat_rate / 100, 2);
  NEW.final_amount := round(v_net + NEW.vat_amount, 2);

  IF NEW.total_paid_amount > NEW.final_amount THEN
    RAISE EXCEPTION 'Invoice paid amount cannot exceed final amount';
  END IF;

  NEW.remaining_amount := round(NEW.final_amount - NEW.total_paid_amount, 2);
  NEW.payment_status := CASE
    WHEN NEW.final_amount > 0 AND NEW.total_paid_amount >= NEW.final_amount THEN 'paid'
    WHEN NEW.total_paid_amount > 0 THEN 'partial'
    ELSE 'unpaid'
  END;

  IF NEW.payment_status = 'paid' AND COALESCE(NEW.status, 'draft') <> 'cancelled' THEN
    NEW.status := 'paid';
  END IF;

  RETURN NEW;
END;
$$;

