-- Reconcile the rebuilt cash ledger to the treasury balances explicitly stored
-- by each organization. This is a visible launch opening-balance entry, not a
-- silent rewrite, and it supplies the historical opening figure that imports
-- did not contain.
DO $$
DECLARE
  r record;
  v_entry uuid;
  v_cash uuid;
  v_equity uuid;
BEGIN
  FOR r IN
    WITH treasury AS (
      SELECT organization_id,COALESCE(currency,'EGP') AS currency,
             CASE WHEN treasury_kind='cash' THEN '1000' ELSE '1010' END AS account_code,
             SUM(COALESCE(current_balance,0)) AS target_balance
      FROM public.bank_accounts
      WHERE COALESCE(is_active,true)
      GROUP BY organization_id,COALESCE(currency,'EGP'),
               CASE WHEN treasury_kind='cash' THEN '1000' ELSE '1010' END
    ), ledger AS (
      SELECT je.organization_id,je.currency,a.account_code,
             SUM(l.debit-l.credit) AS ledger_balance
      FROM public.journal_entries je
      JOIN public.journal_entry_lines l ON l.journal_entry_id=je.id
      JOIN public.chart_of_accounts a ON a.id=l.account_id
      WHERE je.status='posted' AND a.account_code IN ('1000','1010')
        AND je.source_type IS DISTINCT FROM 'launch_opening_balance'
        AND je.entry_date<=CURRENT_DATE
      GROUP BY je.organization_id,je.currency,a.account_code
    )
    SELECT COALESCE(t.organization_id,l.organization_id) AS organization_id,
           COALESCE(t.currency,l.currency) AS currency,
           COALESCE(t.account_code,l.account_code) AS account_code,
           COALESCE(t.target_balance,0) AS target_balance,
           COALESCE(l.ledger_balance,0) AS ledger_balance,
           COALESCE(t.target_balance,0)-COALESCE(l.ledger_balance,0) AS difference
    FROM treasury t
    FULL JOIN ledger l USING(organization_id,currency,account_code)
    WHERE abs(COALESCE(t.target_balance,0)-COALESCE(l.ledger_balance,0))>0.01
  LOOP
    v_cash:=public._resolve_account(r.organization_id,r.account_code);
    v_equity:=public._resolve_account(r.organization_id,'3000');
    IF v_cash IS NULL OR v_equity IS NULL THEN
      RAISE EXCEPTION 'Missing cash/equity account for launch balance in organization %',r.organization_id;
    END IF;
    INSERT INTO public.journal_entries(
      organization_id,entry_number,entry_date,reference_type,description,total_debit,total_credit,
      status,currency,source_type,source_id,functional_currency,fx_rate,posted_at,auto_generated
    ) VALUES (
      r.organization_id,public._next_entry_number(r.organization_id),
      COALESCE((SELECT MIN(entry_date)-1 FROM public.journal_entries
                WHERE organization_id=r.organization_id AND currency=r.currency),CURRENT_DATE),
      'launch_opening_balance','رصيد افتتاحي وتسوية ترحيل عند الإطلاق',
      abs(r.difference),abs(r.difference),'posted',r.currency,
      'launch_opening_balance',gen_random_uuid(),r.currency,1,now(),true
    ) RETURNING id INTO v_entry;
    IF r.difference>0 THEN
      INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
      VALUES
        (v_entry,v_cash,r.difference,0,'تسوية رصيد الخزينة إلى الرصيد المثبت',1),
        (v_entry,v_equity,0,r.difference,'رصيد افتتاحي مقابل',2);
    ELSE
      INSERT INTO public.journal_entry_lines(journal_entry_id,account_id,debit,credit,description,line_order)
      VALUES
        (v_entry,v_equity,abs(r.difference),0,'رصيد افتتاحي مقابل',1),
        (v_entry,v_cash,0,abs(r.difference),'تسوية رصيد الخزينة إلى الرصيد المثبت',2);
    END IF;
    INSERT INTO public.financial_repair_audit(
      migration_key,organization_id,entity_type,entity_id,after_data,reason
    ) VALUES (
      '20260822_financial_launch',r.organization_id,'journal_entry',v_entry,
      jsonb_build_object('currency',r.currency,'account_code',r.account_code,
                         'target_balance',r.target_balance,
                         'ledger_before',r.ledger_balance,'difference',r.difference),
      'Explicit launch opening balance reconciles imported ledger to treasury snapshot'
    );
  END LOOP;
END $$;

-- Fail the migration if any rebuilt header does not equal its lines.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.journal_entries je
    LEFT JOIN public.journal_entry_lines l ON l.journal_entry_id=je.id
    GROUP BY je.id,je.total_debit,je.total_credit
    HAVING abs(je.total_debit-COALESCE(SUM(l.debit),0))>0.01
        OR abs(je.total_credit-COALESCE(SUM(l.credit),0))>0.01
        OR abs(COALESCE(SUM(l.debit),0)-COALESCE(SUM(l.credit),0))>0.01
  ) THEN
    RAISE EXCEPTION 'Journal rebuild validation failed';
  END IF;
END $$;

