// Joined objects and view-only fields are read models, never table columns.
export function pickWriteColumns<T extends object, K extends readonly string[]>(value: T, columns: K): Pick<T, Extract<keyof T, K[number]>> {
  return Object.fromEntries(Object.entries(value).filter(([key, item]) => columns.includes(key) && item !== undefined)) as Pick<T, Extract<keyof T, K[number]>>;
}

